-- Base ficticia para projeto de analise de vendas | MySQL 8.0+
-- Todos os dados sao sinteticos.
CREATE DATABASE IF NOT EXISTS ecommerce_analytics CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE ecommerce_analytics;
SET FOREIGN_KEY_CHECKS = 0;
DROP TABLE IF EXISTS pagamentos;
DROP TABLE IF EXISTS itens_pedido;
DROP TABLE IF EXISTS pedidos;
DROP TABLE IF EXISTS produtos;
DROP TABLE IF EXISTS categorias;
DROP TABLE IF EXISTS clientes;
SET FOREIGN_KEY_CHECKS = 1;

CREATE TABLE clientes (
 id_cliente INT PRIMARY KEY, nome VARCHAR(120) NOT NULL, cidade VARCHAR(80) NOT NULL,
 estado CHAR(2) NOT NULL, data_cadastro DATE NOT NULL,
 INDEX idx_clientes_estado (estado), INDEX idx_clientes_cadastro (data_cadastro)
) ENGINE=InnoDB;
CREATE TABLE categorias (
 id_categoria INT PRIMARY KEY, nome_categoria VARCHAR(80) NOT NULL UNIQUE
) ENGINE=InnoDB;
CREATE TABLE produtos (
 id_produto INT PRIMARY KEY, nome_produto VARCHAR(120) NOT NULL, id_categoria INT NOT NULL,
 preco_atual DECIMAL(10,2) NOT NULL, custo_unitario DECIMAL(10,2) NOT NULL,
 FOREIGN KEY (id_categoria) REFERENCES categorias(id_categoria),
 INDEX idx_produtos_categoria (id_categoria)
) ENGINE=InnoDB;
CREATE TABLE pedidos (
 id_pedido INT PRIMARY KEY, id_cliente INT NOT NULL, data_pedido DATE NOT NULL,
 status_pedido VARCHAR(20) NOT NULL,
 CHECK (status_pedido IN ('entregue','enviado','processando','cancelado')),
 FOREIGN KEY (id_cliente) REFERENCES clientes(id_cliente),
 INDEX idx_pedidos_cliente (id_cliente), INDEX idx_pedidos_data (data_pedido),
 INDEX idx_pedidos_status (status_pedido)
) ENGINE=InnoDB;
CREATE TABLE itens_pedido (
 id_item INT PRIMARY KEY, id_pedido INT NOT NULL, id_produto INT NOT NULL,
 quantidade INT NOT NULL CHECK (quantidade > 0), preco_unitario DECIMAL(10,2) NOT NULL,
 FOREIGN KEY (id_pedido) REFERENCES pedidos(id_pedido),
 FOREIGN KEY (id_produto) REFERENCES produtos(id_produto),
 INDEX idx_itens_pedido (id_pedido), INDEX idx_itens_produto (id_produto)
) ENGINE=InnoDB;
CREATE TABLE pagamentos (
 id_pagamento INT PRIMARY KEY, id_pedido INT NOT NULL UNIQUE,
 forma_pagamento VARCHAR(30) NOT NULL, status_pagamento VARCHAR(20) NOT NULL,
 valor_pago DECIMAL(12,2) NOT NULL,
 CHECK (status_pagamento IN ('aprovado','pendente','estornado','recusado')),
 FOREIGN KEY (id_pedido) REFERENCES pedidos(id_pedido),
 INDEX idx_pagamentos_status (status_pagamento), INDEX idx_pagamentos_forma (forma_pagamento)
) ENGINE=InnoDB;

